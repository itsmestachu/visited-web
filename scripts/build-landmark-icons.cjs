// Generates src/data/landmarks.icons.ts from Mapbox Maki icons (CC0, https://github.com/mapbox/maki).
// Usage: npm pack @mapbox/maki@8.2.0 && tar -xzf mapbox-maki-8.2.0.tgz
//        node scripts/build-landmark-icons.cjs package/icons src/data/landmarks.icons.ts
const fs = require("fs");
const path = require("path");

const [iconsDir, out] = process.argv.slice(2);

// Landmark category → Maki icon (15×15 viewBox).
const ICONS = {
  tower: "observation-tower",
  skyscraper: "building",
  castle: "castle",
  palace: "town-hall",
  church: "religious-christian",
  mosque: "religious-muslim",
  temple: "landmark",
  museum: "museum",
  bridge: "bridge",
  monument: "monument",
  ruins: "historic",
  stadium: "stadium",
  theatre: "theatre",
  lighthouse: "lighthouse",
  nature: "mountain",
  attraction: "star",
};

const decode = (d) => d.replace(/&#x[0-9a-f]+;/gi, " ").replace(/\s+/g, " ").trim();

const entries = Object.entries(ICONS).map(([category, icon]) => {
  const svg = fs.readFileSync(path.join(iconsDir, `${icon}.svg`), "utf8");
  if (/<(circle|rect|polygon|ellipse|line)\b|transform=/.test(svg)) throw new Error(`${icon}: only plain paths are supported`);
  const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => decode(m[1])).join(" ");
  return `  ${category}: "${d}",`;
});

fs.writeFileSync(
  out,
  `// Generated by scripts/build-landmark-icons.cjs from Mapbox Maki 8.2.0 (CC0). Paths use a 15×15 viewBox.
import type { LandmarkCategory } from "./data.types";

export const LANDMARK_ICON_SIZE = 15;

export const LANDMARK_ICONS: Record<LandmarkCategory, string> = {
${entries.join("\n")}
};
`,
);
console.log(`${entries.length} icons → ${out}`);
